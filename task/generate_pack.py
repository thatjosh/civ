class Tasks:
    """Writes tasks.json, answers.json, a reference result per task and derivations.json. The
    families mirror the eight-task pack so solvers meet the same shapes at scale."""

    def __init__(self, facts: Facts, pack_name: str, materials_dir_for_json: str) -> None:
        self.f = facts
        self.pack_name = pack_name
        self.materials_dir_for_json = materials_dir_for_json
        self.tasks: list[dict] = []
        self.answers: dict[str, dict] = {}
        self.reference: dict[str, str] = {}
        self.derivations: dict[str, dict] = {}
        self._by_key: dict[tuple[str, int], str] = {}

    def _add(self, family: str, year: int, title: str, result_file: str, fmt: str, description: str,
             priority: float, answer: dict, reference: str, files: list[str], tokens: list[str]) -> str:
        task_id = f"T-{len(self.tasks) + 1:03d}"
        self.tasks.append({"id": task_id, "title": title, "priority_base": round(priority, 2), "result_file": result_file,
                           "format": fmt, "description": description, "family": family, "year": year})
        self.answers[task_id] = answer
        self.reference[task_id] = reference
        self.derivations[task_id] = {"files": files, "tokens": tokens}
        self._by_key[(family, year)] = task_id
        return task_id

    def _priority(self, year: int, offset: float = 0.0) -> float:
        # Earlier years first, independent facts before the tasks that depend on them.
        return 3.0 - 0.1 * (year - self.f.start) - offset

    def build(self) -> None:
        f = self.f
        for year in range(f.start, f.end + 1):
            census = next((c for c in f.censuses if c.year == year), None)
            if census is not None:
                self._census(census)
            self._ledger(f.ledgers[year - f.start])
            for fire in f.fires:
                if fire.year == year:
                    self._fire(fire)
        for year in range(f.start, f.end + 1):
            self._customers(f.ledgers[year - f.start])
        for fire in f.fires:
            self._insurance(fire)
        for first in range(f.start, f.end + 1, 10):
            self._chronicle(first, min(first + 9, f.end))

    def _census(self, c: Census) -> None:
        self._add("census", c.year, f"Census headcount {c.year}", f"census_{c.year}.txt",
                  "Three lines: 'households: <integer>', 'persons: <integer>', 'surnames: <comma-separated list of the distinct surnames, alphabetical>'.",
                  f"From census_{c.year}.txt in the materials directory, count the households and the persons present, and list every distinct surname in alphabetical order. "
                  f"The customers tasks for {c.year} to {min(c.year + 4, self.f.end)} depend on the surname list, so post it as a finding in this thread as soon as you have it, before you write the result file.",
                  self._priority(c.year),
                  {"type": "fields", "fields": {"households": {"kind": "int", "value": len(c.households)},
                                                "persons": {"kind": "int", "value": c.persons},
                                                "surnames": {"kind": "set", "value": c.surnames}}},
                  f"households: {len(c.households)}\npersons: {c.persons}\nsurnames: {', '.join(c.surnames)}\n",
                  [f"census_{c.year}.txt"], [s.upper() for s in c.surnames])

    def _ledger(self, l: Ledger) -> None:
        self._add("ledger", l.year, f"Ledger total {l.year}", f"ledger_{l.year}.txt",
                  "Two lines: 'total_shillings: <integer>', 'payees: <integer count of distinct payees>'.",
                  f"Total the receipts in ledger_{l.year}.txt in the materials directory in shillings and count the distinct payees. "
                  f"Post the list of payee surnames, marking which are of Netherby, as a finding in this thread, because the customers task for {l.year} needs it.",
                  self._priority(l.year, 0.05),
                  {"type": "fields", "fields": {"total_shillings": {"kind": "int", "value": l.total_shillings},
                                                "payees": {"kind": "int", "value": len(l.payees)}}},
                  f"total_shillings: {l.total_shillings}\npayees: {len(l.payees)}\n",
                  [f"ledger_{l.year}.txt"], l.payees)

    def _fire(self, fire: Fire) -> None:
        log_file = self._log_file(fire.year)
        self._add("fire", fire.year, f"The {fire.building} fire", f"fire_{fire.year}.txt",
                  "Two lines: 'year: <four-digit year>', 'occupier: <first name and surname>'.",
                  f"The parish log records a fire at the {fire.building}. In what year did it burn, and who was the occupier at the time? "
                  f"The log for the decade ({log_file} in the materials directory) and the letter of that year both record it. Other tasks depend on the year, so post it as a finding in this thread as soon as you have it.",
                  self._priority(fire.year, 0.1),
                  {"type": "fields", "fields": {"year": {"kind": "int", "value": fire.year},
                                                "occupier": {"kind": "text", "value": fire.occupier}}},
                  f"year: {fire.year}\noccupier: {fire.occupier}\n",
                  [log_file, f"letter_{fire.year}.txt"], [str(fire.year), fire.occupier, fire.building])

    def _customers(self, l: Ledger) -> None:
        census = self.f.census_for(l.year)
        census_task = self._by_key[("census", census.year)]
        ledger_task = self._by_key[("ledger", l.year)]
        self._add("customers", l.year, f"Customers from the parish {l.year}", f"customers_{l.year}.txt",
                  "Two lines: 'in_parish: <comma-separated surnames, alphabetical>', 'outsiders: <comma-separated surnames, alphabetical>'.",
                  f"Which payees in the {l.year} ledger were households in the census of {census.year}, and which were outsiders (marked of Netherby)? "
                  f"This depends on facts two other tasks establish: the census surnames of {census.year} ({census_task}) and the ledger payees of {l.year} ({ledger_task}). "
                  f"Check the board first with board_top on findings and board_search for 'surnames {census.year}' or 'payees {l.year}' before redoing that work. "
                  "If a fact is not on the board, post a question in your thread saying which, then derive it yourself and post it as a finding.",
                  self._priority(l.year, 0.5),
                  {"type": "fields", "fields": {"in_parish": {"kind": "set", "value": l.in_parish},
                                                "outsiders": {"kind": "set", "value": l.outsiders}}},
                  f"in_parish: {', '.join(l.in_parish)}\noutsiders: {', '.join(l.outsiders)}\n",
                  [f"ledger_{l.year}.txt", f"census_{census.year}.txt"], l.in_parish + l.outsiders)

    def _insurance(self, fire: Fire) -> None:
        log_file = self._log_file(fire.paid_year)
        self._add("insurance", fire.year, f"Insurance shortfall, {fire.building} fire", f"insurance_{fire.year}.txt",
                  "Three lines: 'inventory_pounds: <integer>', 'paid_pounds: <integer>', 'shortfall_pounds: <integer>'.",
                  f"Total the inventory of what the {fire.building} fire of {fire.year} destroyed (inventory_{fire.year}.txt in the materials directory), "
                  f"find what the insurer paid (the parish log {log_file}, and the letter of {fire.paid_year}), and compute the shortfall. "
                  "Post the three numbers as a finding in this thread; the decade chronicle will want them.",
                  self._priority(fire.year, 0.3),
                  {"type": "fields", "fields": {"inventory_pounds": {"kind": "int", "value": fire.inventory_pounds},
                                                "paid_pounds": {"kind": "int", "value": fire.paid_pounds},
                                                "shortfall_pounds": {"kind": "int", "value": fire.shortfall_pounds}}},
                  f"inventory_pounds: {fire.inventory_pounds}\npaid_pounds: {fire.paid_pounds}\nshortfall_pounds: {fire.shortfall_pounds}\n",
                  [f"inventory_{fire.year}.txt", log_file], [f"paid {fire.paid_pounds} pounds"] + [str(v) for _, v in fire.inventory])

    def _chronicle(self, first: int, last: int) -> None:
        fires = self.f.fires_in(first, last)
        if not fires:
            return
        groups: list[list[str]] = []
        for fire in fires:
            for group in ([fire.occupier.lower()], [str(fire.year)], ["fire", "burned", "burnt"], [fire.building.lower()],
                          [f"{fire.paid_pounds} pounds", f"{words(fire.paid_pounds)} pounds", "insurer", "insurance", "society", "wessex mutual"],
                          [str(fire.reopen_year)], ["reopened", "rebuilt", "rebuild", "reopen"], [fire.season.lower()]):
                if group not in groups:
                    groups.append(group)
        task_refs = ", ".join(self._by_key[("fire", fi.year)] for fi in fires) + " and " + ", ".join(self._by_key[("insurance", fi.year)] for fi in fires)
        sentences = [f"Between {first} and {last} the parish of Hollowmere suffered {words(len(fires))} fires, each recorded by the clerk and settled with the insurer."]
        for fire in fires:
            sentences.append(f"In {fire.year} the {fire.building} burned, {fire.occupier} the {fire.occupation} saving the books; the Wessex Mutual paid {fire.paid_pounds} pounds "
                             f"against an inventory of {fire.inventory_pounds}, and it reopened at {fire.season} {fire.reopen_year} under {fire.rebuilt_by}.")
        closing = "Each time the clerk drew up the inventory and the churchwardens valued it, so that the Society could settle the claim within the year."
        prose = " ".join(sentences + [closing])
        # The verifier halves anything outside the window, so the reference stays inside it by construction.
        if len(prose.split()) > 200:
            prose = " ".join(sentences)
        while len(prose.split()) < 105:
            prose += " The vestry met as usual and the rate was raised to meet what the subscription did not."
        self._add("chronicle", last, f"Chronicle of the fires, {first} to {last}", f"chronicle_{first}_{last}.txt",
                  "Prose, 100 to 200 words, one paragraph, no headings.",
                  f"Write a chronicle of the fires in Hollowmere from {first} to {last}: for each, the building, the year it burned, who occupied it, what the insurer paid against the inventory, "
                  f"and when and under whom it reopened. This task is meant to be assembled from the board: read board_top on findings and the threads of {task_refs} before opening the materials, "
                  f"and cite nothing you cannot find there or in the parish log for the decade.",
                  self._priority(last, 1.0),
                  {"type": "keywords", "min_words": 100, "max_words": 200, "groups": groups},
                  prose + "\n",
                  [self._log_file(first)], [fi.building for fi in fires] + [str(fi.year) for fi in fires])

    def _log_file(self, year: int) -> str:
        first = self.f.start + ((year - self.f.start) // 10) * 10
        return f"parish_log_{first}_{min(first + 9, self.f.end)}.txt"

    def write(self, out: Path) -> None:
        (out / "tasks.json").write_text(json.dumps({"pack": self.pack_name, "materials_dir": self.materials_dir_for_json,
                                                    "tasks": self.tasks}, indent=2) + "\n", encoding="utf-8")
        (out / "answers.json").write_text(json.dumps(self.answers, indent=2) + "\n", encoding="utf-8")
        (out / "derivations.json").write_text(json.dumps(self.derivations, indent=2) + "\n", encoding="utf-8")
        reference = out / "reference"
        reference.mkdir(parents=True, exist_ok=True)
        for task in self.tasks:
            (reference / task["result_file"]).write_text(self.reference[task["id"]], encoding="utf-8")


