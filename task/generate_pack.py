def generate(years: int, start: int, seed: int, out: Path) -> dict:
    """Write the pack and return its counts: {"characters", "tasks", "files", "families"}."""
    out = Path(out)
    facts = FactsGenerator(start, years, seed).build()
    files = Prose(facts).files()
    materials = out / "materials"
    materials.mkdir(parents=True, exist_ok=True)
    for stale in materials.glob("*.txt"):
        stale.unlink()
    for name, text in files.items():
        (materials / name).write_text(text, encoding="utf-8")
    try:
        materials_for_json = os.path.relpath(materials, REPO_ROOT)
    except ValueError:
        materials_for_json = str(materials)
    tasks = Tasks(facts, f"hollowmere-{years}y", materials_for_json)
    tasks.build()
    tasks.write(out)
    families: dict[str, int] = {}
    for task in tasks.tasks:
        families[task["family"]] = families.get(task["family"], 0) + 1
    return {"characters": sum(len(t) for t in files.values()), "tasks": len(tasks.tasks), "files": len(files), "families": families}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--years", type=int, default=20)
    parser.add_argument("--start", type=int, default=1850)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "task" / "packs" / "soak-20y")
    args = parser.parse_args(argv)
    counts = generate(args.years, args.start, args.seed, args.out)
    fams = ", ".join(f"{k} {v}" for k, v in sorted(counts["families"].items()))
    print(f"wrote {args.out}: {counts['files']} material files, {counts['characters']} characters, {counts['tasks']} tasks ({fams})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
