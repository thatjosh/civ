class Prose:
    """Writes the clerk's files from the facts. Every answer-bearing number appears in exactly the
    form the task expects to be read from the materials, and nothing in the filler contradicts it."""

    def __init__(self, facts: Facts) -> None:
        self.f = facts

    def files(self) -> dict[str, str]:
        out: dict[str, str] = {}
        for census in self.f.censuses:
            out[f"census_{census.year}.txt"] = self.census(census)
        for ledger in self.f.ledgers:
            out[f"ledger_{ledger.year}.txt"] = self.ledger(ledger)
        for fire in self.f.fires:
            out[f"inventory_{fire.year}.txt"] = self.inventory(fire)
        for year in range(self.f.start, self.f.end + 1):
            out[f"vestry_minutes_{year}.txt"] = self.vestry(year)
            out[f"letter_{year}.txt"] = self.letter(year)
        decade_starts = range(self.f.start, self.f.end + 1, 10)
        for first in decade_starts:
            last = min(first + 9, self.f.end)
            out[f"parish_log_{first}_{last}.txt"] = self.log(first, last)
        out["00_README.txt"] = self.readme(sorted(out))
        return out

    def readme(self, names: list[str]) -> str:
        lines = [f"HOLLOWMERE PARISH RECORDS, {self.f.start} TO {self.f.end}",
                 "An archive assembled for the civ soak. Everything here is fictional.", "", "Files"]
        for name in names:
            kind = name.split("_")[0]
            note = {"census": "household census of 30 March", "ledger": "the mill's receipts for the year",
                    "inventory": "what a fire destroyed, with valuations", "vestry": "the vestry's minutes for the year",
                    "letter": "a letter of the year", "parish": "the clerk's dated log for the decade"}.get(kind, "")
            lines.append(f"  {name:<34} {note}")
        lines += ["", "Conventions", "  Dates in the log and the ledgers are written year-month-day.",
                  "  Money is in pounds and shillings; twenty shillings make a pound.",
                  "  Surnames in the census are written in capitals.",
                  "  Payees from outside the parish are marked (of Netherby) in the ledgers.", ""]
        return "\n".join(lines)

    def census(self, c: Census) -> str:
        lines = [f"HOLLOWMERE PARISH. CENSUS OF 30 MARCH {c.year}.", f"Enumerator: {self.f.clerk}, parish clerk.",
                 "Each entry gives the dwelling, the head of household in capitals, age and occupation, then the other persons present.", ""]
        for i, h in enumerate(c.households, 1):
            others = "; ".join(f"{name}, {age}" for name, age in h.others)
            tail = f" Others: {others}." if others else ""
            lines.append(f"Household {i}. {h.dwelling}. {h.surname.upper()}, {h.head}, {h.age}, {h.occupation}.{tail} Persons: {h.persons}.")
        lines += ["", "Enumerator's note: no house in the parish was found empty. Netherby, across the river, is a separate parish and is not counted here.", ""]
        return "\n".join(lines)

    def ledger(self, l: Ledger) -> str:
        lines = [f"HOLLOWMERE MILL. LEDGER OF RECEIPTS FOR THE YEAR {l.year}.",
                 f"Kept by {l.keeper}. Sums in shillings. Payees from outside the parish are marked (of Netherby).", "",
                 f"{'Date':<12}{'Payee':<12}{'Description':<44}Shillings"]
        for e in l.entries:
            desc = e.description + (" (of Netherby)" if e.outsider else "")
            lines.append(f"{e.date:<12}{e.payee:<12}{desc:<44}{e.shillings:>9}")
        lines += ["", f"Closed at Christmas {l.year}. The total is not carried here; the miller kept it in his head.", ""]
        return "\n".join(lines)

    def inventory(self, fire: Fire) -> str:
        lines = [f"INVENTORY OF THE CONTENTS OF THE {fire.building.upper()} LOST BY FIRE ON {fire.date}.",
                 f"Drawn up by {self.f.clerk}, parish clerk, in {fire.paid_year}. Valued by {fire.occupier} and the churchwardens.",
                 "Sums in pounds.", "", f"{'Item':<40}Pounds"]
        for item, value in fire.inventory:
            lines.append(f"{item:<40}{value:>6}")
        lines += ["", "The valuers have not carried a total; the Society's clerk will add it.", ""]
        return "\n".join(lines)

    def vestry(self, year: int) -> str:
        lines = [f"HOLLOWMERE VESTRY. MINUTES FOR THE YEAR {year}.", f"Taken by {self.f.clerk}, parish clerk.", ""]
        for i, (item, pounds, shillings) in enumerate(self.f.vestry[year], 1):
            lines.append(f"{i}. Agreed {item}; cost {pounds} pounds {shillings} shillings, to be met from the rate.")
        lines += ["", "The churchwardens signed the book and the meeting closed with prayer.", ""]
        return "\n".join(lines)

    def letter(self, year: int) -> str:
        f = self.f
        census = f.census_for(year)
        writer = f"{['Edmund', 'Ruth', 'Thomas', 'Agnes'][year % 4]} {census.surnames[year % len(census.surnames)]}"
        paragraphs = [f"Hollowmere, {['14 January', '2 May', '18 August', '30 November'][year % 4]} {year}", "", "My dear friend,", ""]
        paid = [fi for fi in f.fires if fi.paid_year == year]
        burned = [fi for fi in f.fires if fi.year == year]
        reopened = [fi for fi in f.fires if fi.reopen_year == year]
        if burned:
            fi = burned[0]
            paragraphs.append(f"You will have heard that the {fi.building} burned this year, on the night of {fi.date}. "
                              f"No lives were lost, and {fi.occupier} the {fi.occupation} saved the books, which is more than most would have done. "
                              "The clerk is drawing up an inventory for the Society.")
        if paid:
            fi = paid[0]
            paragraphs.append(f"The Society has settled the {fi.building} claim at last. They paid {words(fi.paid_pounds)} pounds against an inventory of "
                              f"{words(fi.inventory_pounds)}, and the {words(fi.shortfall_pounds)} pounds short will be made up by subscription in the parish, as before.")
        if reopened:
            fi = reopened[0]
            paragraphs.append(f"The {fi.building} reopened at {fi.season}, with {fi.rebuilt_by} as {fi.occupation}. The masons were from Netherby again.")
        if not (burned or paid or reopened):
            paragraphs.append(f"Nothing out of the way has happened this year. The census of {census.year} still stands at {words(len(census.households))} households, "
                              f"and the mill grinds on under {f.ledgers[year - f.start].keeper}. The harvest was {['middling', 'good', 'late', 'thin'][year % 4]}.")
        paragraphs += ["", "With my respectful good wishes,", writer, ""]
        return "\n".join(paragraphs)

    def log(self, first: int, last: int) -> str:
        lines = [f"HOLLOWMERE PARISH LOG, {first} TO {last}.", f"Kept by {self.f.clerk}, parish clerk. One entry per line, dated year-month-day.", ""]
        for year in range(first, last + 1):
            for date, text in self.f.log[year]:
                lines.append(f"{date}  {text}")
        lines.append("")
        return "\n".join(lines)


