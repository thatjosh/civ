"""Generate a synthetic Hollowmere archive large enough to soak the civilisation on.

    python task/generate_pack.py --years 20 --start 1850 --seed 7 --out task/packs/soak-20y

Facts come first and the prose is written from them, so every hidden answer is exact and the
pack can be regenerated byte for byte from its seed. Three objects own the three concerns:
``Facts`` draws the parish (censuses, ledgers, fires, log entries) from a seeded generator,
``Prose`` turns those facts into the clerk's files, and ``Tasks`` writes the task list, the
answers, a reference result per task and a record of which file each answer comes from. The
task families are the eight-task demo pack's, repeated across the years, so a solver that has
learnt the small pack already knows the shape of the large one.
"""

