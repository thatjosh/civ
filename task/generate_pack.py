def words(n: int) -> str:
    """Numbers in words, for the keyword groups that accept "eighty pounds" as well as "80 pounds"."""
    if n in WORDS:
        return WORDS[n]
    if n < 100:
        return f"{WORDS[n - n % 10]} {WORDS[n % 10]}"
    hundreds, rest = divmod(n, 100)
    return f"{WORDS[hundreds]} hundred" + (f" and {words(rest)}" if rest else "")


# --- facts ---------------------------------------------------------------------------------------


@dataclass
class Household:
    dwelling: str
    surname: str
    head: str
    age: int
    occupation: str
    others: list[tuple[str, int]]

    @property
    def persons(self) -> int:
        return 1 + len(self.others)


@dataclass
class Census:
    year: int
    households: list[Household]

    @property
    def surnames(self) -> list[str]:
        return sorted({h.surname for h in self.households})

    @property
    def persons(self) -> int:
        return sum(h.persons for h in self.households)


@dataclass
class LedgerEntry:
    date: str
    payee: str
    outsider: bool
    description: str
    shillings: int


@dataclass
class Ledger:
    year: int
    keeper: str
    entries: list[LedgerEntry]

    @property
    def total_shillings(self) -> int:
        return sum(e.shillings for e in self.entries)

    @property
    def payees(self) -> list[str]:
        return sorted({e.payee for e in self.entries})

    @property
    def in_parish(self) -> list[str]:
        return sorted({e.payee for e in self.entries if not e.outsider})

    @property
    def outsiders(self) -> list[str]:
        return sorted({e.payee for e in self.entries if e.outsider})


@dataclass
class Fire:
    year: int
    date: str
    building: str
    occupier: str
    occupation: str
    inventory: list[tuple[str, int]]
    paid_pounds: int
    paid_year: int
    reopen_year: int
    season: str
    season_date: str
    rebuilt_by: str

    @property
    def inventory_pounds(self) -> int:
        return sum(v for _, v in self.inventory)

    @property
    def shortfall_pounds(self) -> int:
        return self.inventory_pounds - self.paid_pounds


@dataclass
class Facts:
    start: int
    years: int
    censuses: list[Census] = field(default_factory=list)
    ledgers: list[Ledger] = field(default_factory=list)
    fires: list[Fire] = field(default_factory=list)
    # year -> list of (date, text) log lines, including births, burials, fires and reopenings
    log: dict[int, list[tuple[str, str]]] = field(default_factory=dict)
    vestry: dict[int, list[tuple[str, int, int]]] = field(default_factory=dict)
    clerk: str = ""

    @property
    def end(self) -> int:
        return self.start + self.years - 1

    def census_for(self, year: int) -> Census:
        """The census at or before a year; the first census when none precedes it."""
        before = [c for c in self.censuses if c.year <= year]
        return before[-1] if before else self.censuses[0]

    def fires_in(self, first: int, last: int) -> list[Fire]:
        return [f for f in self.fires if first <= f.year <= last]


class FactsGenerator:
    """Draws the parish from a seeded generator. Censuses every five years with a stable core of
    households and some churn, a ledger every year, a fire every fourth year from the third, and
    a log of births, burials and vestry business around them."""

    FIRE_EVERY = 4
    FIRE_FIRST_OFFSET = 2
    CENSUS_EVERY = 5

    def __init__(self, start: int, years: int, seed: int) -> None:
        self.rng = random.Random(seed)
        self.facts = Facts(start=start, years=years)
        self._used_buildings: list[tuple[str, str]] = []

    def build(self) -> Facts:
        f = self.facts
        f.clerk = f"{self.rng.choice(MALE_NAMES)} Wick"
        self._censuses()
        self._fires()
        for year in range(f.start, f.end + 1):
            f.ledgers.append(self._ledger(year))
            f.log[year] = self._log_lines(year)
            f.vestry[year] = self._vestry(year)
        return f

    # Censuses: a core of surnames carried forward, a few households leaving and arriving.
    def _censuses(self) -> None:
        f = self.facts
        surnames = self.rng.sample(PARISH_SURNAMES, 14)
        for year in range(f.start, f.end + 1, self.CENSUS_EVERY):
            if f.censuses:
                leaving = self.rng.sample(surnames, self.rng.randint(1, 3))
                pool = [s for s in PARISH_SURNAMES if s not in surnames]
                arriving = self.rng.sample(pool, self.rng.randint(1, 4))
                surnames = [s for s in surnames if s not in leaving] + arriving
            dwellings = self.rng.sample(DWELLINGS, len(surnames))
            households = []
            for dwelling, surname in zip(dwellings, surnames):
                female_head = self.rng.random() < 0.15
                head = self.rng.choice(FEMALE_NAMES if female_head else MALE_NAMES)
                age = self.rng.randint(24, 68)
                occupation = self.rng.choice(OCCUPATIONS)
                others: list[tuple[str, int]] = []
                if not female_head and self.rng.random() < 0.8:
                    others.append((self.rng.choice(FEMALE_NAMES), max(20, age - self.rng.randint(0, 6))))
                for _ in range(self.rng.randint(0, 4)):
                    others.append((self.rng.choice(MALE_NAMES + FEMALE_NAMES), self.rng.randint(1, 19)))
                households.append(Household(dwelling, surname, head, age, occupation, others))
            f.censuses.append(Census(year, households))

    def _fires(self) -> None:
        f = self.facts
        for year in range(f.start + self.FIRE_FIRST_OFFSET, f.end + 1, self.FIRE_EVERY):
            building, occupation = self.rng.choice([b for b in BUILDINGS if b not in self._used_buildings])
            self._used_buildings.append((building, occupation))
            census = f.census_for(year)
            occupier_surname = self.rng.choice(census.surnames)
            occupier = f"{self.rng.choice(MALE_NAMES)} {occupier_surname}"
            items = self.rng.sample(INVENTORY_ITEMS, self.rng.randint(4, 6))
            inventory = [(item, self.rng.randint(3, 45)) for item in items]
            total = sum(v for _, v in inventory)
            paid = max(5, total - self.rng.randint(6, max(7, total // 3)))
            gap = self.rng.randint(1, 2)
            season, season_date = self.rng.choice(SEASONS)
            rebuilt_by = f"{self.rng.choice(MALE_NAMES)} {occupier_surname}"
            date = f"{year}-{self.rng.randint(1, 12):02d}-{self.rng.randint(1, 28):02d}"
            f.fires.append(Fire(year, date, building, occupier, occupation, inventory, paid, year + 1, year + gap,
                                season, season_date, rebuilt_by))

    def _ledger(self, year: int) -> Ledger:
        f = self.facts
        census = f.census_for(year)
        keeper = next((fi.occupier for fi in f.fires if fi.building == "Mill" and fi.year >= year), None)
        keeper = keeper or f"{self.rng.choice(MALE_NAMES)} {self.rng.choice(census.surnames)}"
        outsiders = self.rng.sample(OUTSIDER_SURNAMES, self.rng.randint(1, 3))
        entries: list[LedgerEntry] = []
        count = self.rng.randint(50, 62)
        day_step = 365 // count
        for i in range(count):
            doy = min(364, i * day_step + self.rng.randint(0, max(1, day_step - 1)))
            month, day = divmod(doy, 30)
            date = f"{year}-{min(12, month + 1):02d}-{min(28, day + 1):02d}"
            outsider = self.rng.random() < 0.15
            payee = self.rng.choice(outsiders) if outsider else self.rng.choice(census.surnames)
            goods = self.rng.choice(LEDGER_GOODS).format(n=self.rng.randint(1, 12))
            entries.append(LedgerEntry(date, payee, outsider, goods, self.rng.randint(1, 20)))
        entries.sort(key=lambda e: e.date)
        return Ledger(year, keeper, entries)

    def _log_lines(self, year: int) -> list[tuple[str, str]]:
        f = self.facts
        census = f.census_for(year)
        lines: list[tuple[str, str]] = []
        for _ in range(self.rng.randint(13, 17)):
            kind = self.rng.random()
            surname = self.rng.choice(census.surnames)
            date = f"{year}-{self.rng.randint(1, 12):02d}-{self.rng.randint(1, 28):02d}"
            if kind < 0.35:
                lines.append((date, f"Baptism: {self.rng.choice(MALE_NAMES + FEMALE_NAMES)}, child of {self.rng.choice(MALE_NAMES)} and {self.rng.choice(FEMALE_NAMES)} {surname}."))
            elif kind < 0.6:
                lines.append((date, f"Burial: {self.rng.choice(MALE_NAMES + FEMALE_NAMES)} {surname}, aged {self.rng.randint(1, 84)}."))
            elif kind < 0.75:
                other = self.rng.choice(census.surnames)
                lines.append((date, f"Marriage: {self.rng.choice(MALE_NAMES)} {surname} to {self.rng.choice(FEMALE_NAMES)} {other}."))
            else:
                lines.append((date, f"Vestry agreed {self.rng.choice(VESTRY_ITEMS)}; cost {self.rng.randint(1, 20)} pounds {self.rng.randint(0, 19)} shillings."))
        for c in f.censuses:
            if c.year == year:
                lines.append((f"{year}-03-30", f"Census taken by the clerk. {words(len(c.households)).capitalize()} households counted."))
        for fire in f.fires:
            if fire.year == year:
                lines.append((fire.date, f"Fire at the {fire.building} in the night. No lives lost. {fire.occupier}, {fire.occupation}, saved the books."))
            if fire.paid_year == year:
                lines.append((f"{year}-{self.rng.randint(1, 6):02d}-{self.rng.randint(1, 28):02d}", f"The Wessex Mutual paid {fire.paid_pounds} pounds on the {fire.building} claim."))
            if fire.reopen_year == year:
                lines.append((f"{year}-{fire.season_date}", f"{fire.season}. The {fire.building} reopened. {fire.rebuilt_by}, {fire.occupation}."))
        lines.sort()
        return lines

    def _vestry(self, year: int) -> list[tuple[str, int, int]]:
        items = self.rng.sample(VESTRY_ITEMS, self.rng.randint(11, 13))
        return [(item, self.rng.randint(0, 30), self.rng.randint(0, 19)) for item in items]


